import { promises as fs } from 'fs';
import * as path from 'path';
import { coreSql, triggerSql } from '../src/sync/sql/generate';

/**
 * Writes a migration holding the change-capture triggers generated from
 * src/sync/sync.config.ts.
 *
 *   npm run sync:migration -- SyncCore --core   (once: tables + functions + triggers)
 *   npm run sync:migration -- SyncAddNotes      (after changing sync.config.ts)
 *
 * The SQL is copied into the migration rather than generated when it runs,
 * so an old migration keeps doing exactly what it did when it shipped. The
 * class carries the trigger statements as a static field; sync.config.spec.ts
 * compares the newest one with what the config generates today, which is
 * what fails a build that changed the config without writing a migration.
 */
const MIGRATIONS_DIR = path.join(__dirname, '../src/database/migrations');

const literal = (sql: string) => '`' + sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';

async function main() {
  const args = process.argv.slice(2);
  const core = args.includes('--core');
  const name = args.find((a) => !a.startsWith('--'));
  if (!name || !/^[A-Z][A-Za-z0-9]*$/.test(name)) {
    throw new Error('Usage: npm run sync:migration -- <PascalCaseName> [--core]');
  }

  const timestamp = Date.now();
  const className = `${name}${timestamp}`;
  const triggers = triggerSql();
  const coreStatements = core ? coreSql() : [];

  const file = `import { MigrationInterface, QueryRunner } from 'typeorm';

/**
 * Change capture for the cloud ⇄ store server sync, generated by
 * scripts/sync-migration.ts from src/sync/sync.config.ts. Do not edit by hand.
 */
export class ${className} implements MigrationInterface {
  name = '${className}';
${core ? `
  static readonly core = [
    ${coreStatements.map(literal).join(',\n    ')},
  ];
` : ''}
  static readonly triggers = [
    ${triggers.map(literal).join(',\n    ')},
  ];

  public async up(queryRunner: QueryRunner): Promise<void> {
    for (const sql of [${core ? `...${className}.core, ` : ''}...${className}.triggers]) {
      await queryRunner.query(sql);
    }
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
${core ? `    for (const table of ${JSON.stringify(triggerTables())}) {
      await queryRunner.query(\`DROP TRIGGER IF EXISTS tnt_sync ON "\${table}"\`);
    }
    await queryRunner.query(\`DROP FUNCTION IF EXISTS ${['tnt_touch(text, uuid, text, uuid, boolean)', 'tnt_delta(uuid, text, uuid, text, numeric)', 'tnt_guard(uuid, text)', 'tnt_now()', 'tnt_role()', 'tnt_applying()'].join(', ')} CASCADE\`);
    await queryRunner.query(\`DROP TABLE IF EXISTS sync_conflicts, sync_parked, sync_counter_deltas, sync_meta, sync_state\`);
    await queryRunner.query(\`DROP SEQUENCE IF EXISTS sync_seq\`);` : `    // The previous trigger migration's functions are not kept anywhere to restore.
    throw new Error('Revert by writing a new sync migration from the earlier config.');`}
  }
}
`;

  const out = path.join(MIGRATIONS_DIR, `${timestamp}-${name}.ts`);
  await fs.writeFile(out, file);
  await writeIndex();
  console.log(`Wrote ${path.relative(process.cwd(), out)} (${coreStatements.length + triggers.length} statements).`);
}

function triggerTables(): string[] {
  const { SYNC_TABLES, SYNC_CHILDREN } = require('../src/sync/sync.config');
  return [...SYNC_TABLES.map((t: { table: string }) => t.table), ...SYNC_CHILDREN.map((c: { table: string }) => c.table)];
}

/** Same index writer as migration-generate.ts: every migration file, oldest first. */
async function writeIndex() {
  const files = (await fs.readdir(MIGRATIONS_DIR))
    .filter((f) => /^\d+-[A-Za-z0-9]+\.ts$/.test(f))
    .sort((a, b) => Number(a.split('-')[0]) - Number(b.split('-')[0]));
  const classes = files.map((f) => {
    const [timestamp, rest] = f.replace(/\.ts$/, '').split('-');
    return { file: f.replace(/\.ts$/, ''), className: `${rest}${timestamp}` };
  });
  const imports = classes.map((c) => `import { ${c.className} } from './${c.file}';`).join('\n');
  const list = classes.map((c) => `  ${c.className},`).join('\n');
  await fs.writeFile(
    path.join(MIGRATIONS_DIR, 'index.ts'),
    `// Generated by scripts/migration-generate.ts — do not edit by hand.\n${imports}\n\nexport const MIGRATIONS: Function[] = [\n${list}\n];\n`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
